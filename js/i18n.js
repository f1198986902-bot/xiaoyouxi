  function readStored() {
    try {
      var v = localStorage.getItem(KEY);
      if (v === "zh" || v === "en") return v;
    } catch (e) {}
    return null;
  }

  function persist() {
    try {
      localStorage.setItem(KEY, lang);
    } catch (e) {}
  }

  function format(s, vars) {
    if (!vars) return s;
    return String(s).replace(/\{(\w+)\}/g, function (_, k) {
      return vars[k] != null ? String(vars[k]) : "";
    });
  }

  function t(key, vars) {
    var table = DICT[lang] || DICT.en;
    var s = table[key];
    if (s == null) s = DICT.en[key];
    if (s == null) s = key;
    return format(s, vars);
  }

  function literal(which, key) {
    var table = DICT[which] || DICT.en;
    return table[key] != null ? table[key] : key;
  }

  lang = readStored() || "en";

  root.I18n = {
    KEY: KEY,
    t: t,
    literal: literal,
    format: format,
    getLang: function () {
      return lang;
    },
    setLang: function (next) {
      if (next !== "en" && next !== "zh") return lang;
      var changed = next !== lang;
      lang = next;
      persist();
      if (changed) {
        var i;
        for (i = 0; i < listeners.length; i++) listeners[i](lang);
      }
      return lang;
    },
    onChange: function (fn) {
      if (typeof fn === "function") listeners.push(fn);
    },
    isZh: function () {
      return lang === "zh";
    }
  };
